def check():
    bad = []
    for acct, dates in NEW.items():
        for d, ls in dates.items():
            if len(ls) > 3: bad.append((acct, d, "too many"))
            for l in ls:
                if len(l) > 120: bad.append((acct, d, f"len={len(l)}"))
    return bad

if __name__ == "__main__":
    bad = check()
    if bad:
        print("LENGTH/COUNT ERRORS:", bad); sys.exit(1)
    mode = sys.argv[1] if len(sys.argv) > 1 else "apply"
    stats = []
    for acct, dates in NEW.items():
        state = json.load(open(f"_state_{acct}_1020.json", encoding="utf-8"))
        by_date = {r["date"]: r for r in (state.get("dailyReviews") or [])}
        for d, lessons in sorted(dates.items()):
            r = by_date.get(d)
            if not r:
                print(f"SKIP {acct} {d}: no existing review"); continue
            payload = {
                "date": d,
                "summary": r.get("summary") or "",
                "bullets": r.get("bullets") or [],
                "lessons": lessons,
                "score": r.get("score"),
            }
            fn = f"_opt_{acct}_{d}.json"
            json.dump(payload, open(fn, "w", encoding="utf-8"), ensure_ascii=False)
            if mode == "dry":
                print(f"[dry] {acct} {d} lessons={len(lessons)}"); continue
            out = subprocess.run(["curl", "-s", "--ssl-no-revoke", "-X", "POST",
                                  f"{HOST}/api/daily_review?account={acct}",
                                  "-H", "Content-Type: application/json",
                                  "-d", f"@{fn}"], capture_output=True, text=True).stdout.strip()
            print(f"{acct:16s} {d} lessons={len(lessons)} -> {out}")
            stats.append((acct, d, out))
    print("\nposted:", len(stats))
